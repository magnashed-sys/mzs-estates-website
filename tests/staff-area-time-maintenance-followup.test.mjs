import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const file=p=>readFileSync(p,'utf8');
test('operational area time entries are real nonfinancial visits, never fictitious properties',()=>{
 const sql=file('supabase/migrations/20261030033000_staff_area_time_ticket_followup.sql');
 assert.match(sql,/alter table public\.mzs_ops_staff_visits\s+add column work_area_id text/);
 assert.match(sql,/alter table public\.mzs_ops_staff_visits alter column property_id drop not null/);
 assert.match(sql,/ops_visit_location_exactly_one/);
 assert.match(sql,/mzs_private\.ops_can_work_on_area\(new\.work_area_id\)/);
 assert.match(sql,/t\.work_area_id is distinct from new\.work_area_id/);
 assert.match(sql,/with\(security_invoker=true,security_barrier=true\)/);
 assert.doesNotMatch(sql,/insert into public\.mzs_estate_properties/i);
 const actions=file('app/staff/actions.ts');
 assert.match(actions,/work_area_id:workAreaId\|\|null/);
 assert.match(actions,/mzs_ops_staff_work_area_directory/);
 const form=file('app/staff/StaffForms.tsx');
 assert.match(form,/areas\.map\(a=><option/);
 assert.match(form,/setLocation\(selected\.work_area_id\?'area:'/);
 assert.match(form,/name="work_area_id" value=\{workAreaId\}/);
 assert.match(form,/isArea\?<input type="hidden" name="unit_id"/);
});
test('maintenance follow-up does not change admin ticket status or authorize suppliers',()=>{
 const sql=file('supabase/migrations/20261030033000_staff_area_time_ticket_followup.sql');
 assert.match(sql,/create table public\.mzs_ops_staff_ticket_notes/);
 assert.match(sql,/ops_staff_ticket_notes_write/);
 assert.match(sql,/created_by=\(select auth\.uid\(\)\)/);
 assert.match(sql,/ops_staff_ticket_note_guard/);
 assert.match(sql,/ops_staff_ticket_note_no_edit/);
 assert.doesNotMatch(sql,/update public\.mzs_ops_maintenance_tickets/i);
 const action=file('app/staff/ticket-note-actions.ts');
 assert.match(action,/addMyMaintenanceProgress/);
 assert.match(action,/\.from\('mzs_ops_staff_ticket_notes'\)/);
 assert.match(action,/ticket\.reported_by!==user\.id/);
 const board=file('app/staff/StaffTaskBoard.tsx');
 assert.match(board,/TicketFollowUp/);
 assert.match(board,/maintenance\.map\(ticket=>/);
 assert.match(board,/ticket\.status!=='closed'/);
 assert.match(board,/addMyMaintenanceProgress/);
 const history=file('app/staff/WorkRegisters.tsx');
 assert.match(history,/data\.staffNotes\.map/);
});
